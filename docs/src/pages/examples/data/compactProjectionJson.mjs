/**
 * Shared helpers for strategy JSON → browser projection build scripts.
 * Keep heavy research fields out of the Vite docs bundle.
 */
import { readFileSync, writeFileSync } from "node:fs"
import { stdout } from "node:process"

/** Pick a subset of fields from a row. */
export function pick(row, fields) {
  return Object.fromEntries(fields.map((field) => [field, row[field]]))
}

/** Deep-strip keys (research-only columns) from nested objects/arrays. */
export function stripHeavy(value, dropKeys) {
  const drop = dropKeys instanceof Set ? dropKeys : new Set(dropKeys ?? [])
  if (Array.isArray(value)) return value.map((entry) => stripHeavy(entry, drop))
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value)
        .filter(([key]) => !drop.has(key))
        .map(([key, nested]) => [key, stripHeavy(nested, drop)]),
    )
  }
  return value
}

/**
 * Read strategy JSON, build a compact object, write a generated ESM module.
 *
 * @param {object} options
 * @param {string} options.sourcePath
 * @param {string} options.outputPath
 * @param {string} options.exportName  const name in the generated file
 * @param {(source: object) => object} options.buildCompact
 * @param {string} [options.builderName]  for the file header comment
 */
export function writeCompactStrategyModule({
  sourcePath,
  outputPath,
  exportName,
  buildCompact,
  builderName = "compactProjectionJson",
}) {
  const source = JSON.parse(readFileSync(sourcePath, "utf8"))
  const compact = buildCompact(source)
  const output =
    `// Generated by ${builderName}. Do not edit by hand.\n` +
    `// Runtime projection of the full audited strategy dataset; parity is unit-tested.\n` +
    `const ${exportName} = ${JSON.stringify(compact, null, 2)}\n\n` +
    `export default ${exportName}\n`
  writeFileSync(outputPath, output)
  stdout.write(`Wrote ${outputPath}\n`)
}

