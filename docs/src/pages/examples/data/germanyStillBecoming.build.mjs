import { readFileSync, writeFileSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { stdout } from "node:process"
import { fileURLToPath } from "node:url"

const dataDirectory = dirname(fileURLToPath(import.meta.url))
const sourcePath = resolve(dataDirectory, "../../../../strategy/germany_history_river_dataset.json")
const outputPath = resolve(dataDirectory, "germanyStillBecoming.source.generated.js")
const source = JSON.parse(readFileSync(sourcePath, "utf8"))

/** Research-only fields dropped from the browser projection. */
const DROP_KEYS = new Set([
  "atom_ids",
  "modern_land_codes",
  "nuts2_codes",
  "area_km2_2022",
  "gdp_eur_m_2022",
  "population_2022",
  "area_km2_historical",
  "gdp_historical",
  "population_high",
  "population_historical_mid",
  "population_low",
  "population_reference_year",
])

function stripHeavy(value) {
  if (Array.isArray(value)) return value.map(stripHeavy)
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value)
        .filter(([key]) => !DROP_KEYS.has(key))
        .map(([key, nested]) => [key, stripHeavy(nested)]),
    )
  }
  return value
}

function pick(row, fields) {
  return Object.fromEntries(fields.map((field) => [field, row[field]]))
}

const compact = {
  generated_from: "docs/strategy/germany_history_river_dataset.json",
  metadata: source.metadata,
  metric_definitions: source.metric_definitions,
  stages: source.stages.map((stage) => pick(stage, [
    "stage_id",
    "stage_order",
    "benchmark",
    "label",
    "focus",
    "description",
    "default_x",
    "source_key",
  ])),
  nodes: stripHeavy(source.nodes),
  links: stripHeavy(source.links),
  events: source.events.map((event) => pick(event, [
    "event_id",
    "date",
    "title",
    "event_type",
    "stage_before",
    "stage_after",
    "affected_streams",
    "map_instruction",
    "confidence",
    "notes",
    "source_key",
  ])),
  external_flows: stripHeavy(source.external_flows),
  endpoint_atoms: stripHeavy(source.endpoint_atoms),
  palette: source.palette.map((entry) => pick(entry, [
    "palette_key",
    "hex",
    "usage",
  ])),
  sources: source.sources.map((reference) => pick(reference, [
    "source_key",
    "title",
    "publisher",
    "url",
    "used_for",
    "quality_note",
    "source_type",
    "accessed",
  ])),
}

const output = `// Generated by germanyStillBecoming.build.mjs. Do not edit by hand.\n` +
  `// Runtime projection of the full audited strategy dataset; parity is unit-tested.\n` +
  `const germanyStillBecomingSource = ${JSON.stringify(compact, null, 2)}\n\n` +
  `export default germanyStillBecomingSource\n`

writeFileSync(outputPath, output)
stdout.write(`Wrote ${outputPath}\n`)
