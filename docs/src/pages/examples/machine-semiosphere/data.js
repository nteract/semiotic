/**
 * Deterministic, sanitized fixtures for The Machine Semiosphere.
 *
 * Incident facts are compact transcriptions of the public source registry in
 * the design contract. Editorial groupings and hypotheses are labeled in the
 * datum itself. Nothing in this module contains operational intrusion detail,
 * live endpoints, credentials, or runtime research dependencies.
 */

function deepFreeze(value) {
  if (!value || typeof value !== "object" || Object.isFrozen(value)) return value
  for (const child of Object.values(value)) deepFreeze(child)
  return Object.freeze(value)
}

