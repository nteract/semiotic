#!/usr/bin/env node
/**
 * Generate the machine-readable contract reference from its published schema.
 *
 * Usage:
 *   node scripts/generate-artifact-contract-reference.mjs
 *   node scripts/generate-artifact-contract-reference.mjs --check
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, relative, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, "..")
const schemaPath = resolve(root, "spec/v0.1/artifact-contract.schema.json")
const outputPath = resolve(root, "ai/artifact-contract-reference.md")
const checkOnly = process.argv.includes("--check")

const POLICY_KEYS = [
  "x-semiotic-supplied-by",
  "x-semiotic-derivable",
  "x-semiotic-model-may-propose",
  "x-semiotic-human-review"
]

function readJson(path) {
  return JSON.parse(readFileSync(path, "utf8"))
}

function refName(ref) {
  return String(ref).split("/").at(-1) ?? String(ref)
}

function typeLabel(node) {
  if (node.$ref) return refName(node.$ref)
  if (Object.prototype.hasOwnProperty.call(node, "const")) {
    return `literal ${JSON.stringify(node.const)}`
  }
  if (Array.isArray(node.enum)) {
    return node.enum.map((value) => JSON.stringify(value)).join(" \u00b7 ")
  }
  if (node.type === "array") return `array<${typeLabel(node.items ?? {})}>`
  if (Array.isArray(node.type)) return node.type.join(" | ")
  if (node.type) return String(node.type)
  if (Array.isArray(node.anyOf)) {
    return node.anyOf.map(typeLabel).join(" | ")
  }
  return "value"
}

function escapeCell(value) {
  return String(value ?? "")
    .replaceAll("|", "\\|")
    .replace(/\s+/g, " ")
    .trim()
}

function propertyRows(schema, prefix) {
  if (!schema?.properties) return []
  const required = new Set(schema.required ?? [])
  return Object.entries(schema.properties).map(([name, property]) => {
    const path = prefix ? `${prefix}.${name}` : name
    const missing = POLICY_KEYS.filter((key) => !(key in property))
    if (missing.length > 0) {
      throw new Error(
        `${path} is missing field-policy metadata: ${missing.join(", ")}`
      )
    }
    return [
      `\`${path}\``,
      typeLabel(property),
      required.has(name) ? "yes" : "no",
      property["x-semiotic-supplied-by"].join(", "),
      property["x-semiotic-derivable"] ? "yes" : "no",
      property["x-semiotic-model-may-propose"] ? "yes" : "no",
      property["x-semiotic-human-review"],
      property.description ?? ""
    ]
  })
}

function renderTable(rows) {
  const header = [
    "| Field | Type | Required | Supplied by | Derivable | Model proposal | Human review | Meaning |",
    "|---|---|:---:|---|:---:|:---:|---|---|"
  ]
  return [
    ...header,
    ...rows.map((row) => `| ${row.map(escapeCell).join(" | ")} |`)
  ].join("\n")
}

function renderReference(schema) {
  const sections = []
  const rootRows = propertyRows(schema, "")
  sections.push("## Contract fields", "", renderTable(rootRows), "")

  for (const [name, definition] of Object.entries(schema.$defs ?? {})) {
    const rows = propertyRows(definition, name)
    if (rows.length === 0) continue
    sections.push(`## ${name}`, "", renderTable(rows), "")
  }

  return [
    "# Artifact Contract schema reference",
    "",
    "<!-- Generated by scripts/generate-artifact-contract-reference.mjs. Do not edit directly. -->",
    "",
    schema.description,
    "",
    `- Contract version: \`${schema.properties.contractVersion.const}\``,
    `- JSON Schema: \`${relative(root, schemaPath)}\``,
    `- Stable schema identifier: \`${schema.$id}\``,
    "- Unknown, manual, and not-applicable states remain distinct; absence is never reported as a successful check.",
    "- Core objects reject unknown keys. Domain-specific additions belong in the top-level `extensions` object.",
    "",
    ...sections
  ].join("\n")
}

if (!existsSync(schemaPath)) {
  throw new Error(`Missing schema: ${relative(root, schemaPath)}`)
}

const rendered = renderReference(readJson(schemaPath))
if (checkOnly) {
  const current = existsSync(outputPath) ? readFileSync(outputPath, "utf8") : ""
  if (current !== rendered) {
    console.error(
      "Artifact Contract reference is stale. Run: node scripts/generate-artifact-contract-reference.mjs"
    )
    process.exit(1)
  }
  console.log("Artifact Contract reference is current.")
} else {
  writeFileSync(outputPath, rendered)
  console.log(`Wrote ${relative(root, outputPath)}`)
}
