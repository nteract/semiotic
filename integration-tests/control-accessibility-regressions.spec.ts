import { expect, test } from "@playwright/test"
import AxeBuilder from "@axe-core/playwright"

test.beforeEach(async ({ page }) => {
  await page.goto("/control-accessibility-regressions/")
})

test("legend keyboard navigation reaches all groups, matches hover, and survives shrinking", async ({ page }) => {
  const listbox = page.getByRole("listbox", { name: "Color and size" })
  await listbox.getByRole("option", { name: "Blue" }).focus()
  await page.keyboard.press("ArrowDown")
  await expect(listbox.getByRole("option", { name: "Red" })).toBeFocused()
  await page.keyboard.press("ArrowDown")
  await expect(listbox.getByRole("option", { name: "Small" })).toBeFocused()
  await expect(page.getByTestId("legend-hover")).toHaveText("Hovered: Small")
  await page.keyboard.press("Enter")
  await expect(page.getByTestId("legend-selection")).toHaveText("Selected: Small")
  await page.keyboard.press("End")
  await expect(listbox.getByRole("option", { name: "Large" })).toBeFocused()
  // Shrink programmatically to preserve the reader's current focus during a streaming update.
  await page.getByRole("button", { name: "Resize and shrink" }).evaluate((element: HTMLButtonElement) => element.click())
  await expect(listbox.getByRole("option", { name: "Small" })).toBeFocused()
  await expect(listbox.locator("[tabindex='0']")).toHaveCount(1)
  await listbox.getByRole("option", { name: "Red" }).hover()
  await expect(page.getByTestId("legend-hover")).toHaveText("Hovered: Red")
  await page.mouse.move(0, 0)
  await expect(page.getByTestId("legend-hover")).toHaveText("Hovered: None")
  const gradient = page.getByRole("listbox", { name: "Intensity" })
  const bins = gradient.getByRole("option")
  await bins.first().focus()
  await page.keyboard.press("End")
  await expect(bins.last()).toBeFocused()
  await page.keyboard.press("ArrowRight")
  await expect(bins.first()).toBeFocused()
  await page.keyboard.press("ArrowLeft")
  await expect(bins.last()).toBeFocused()
  await page.keyboard.press("Home")
  await expect(bins.first()).toBeFocused()
  await page.keyboard.press("Enter")
  await expect(page.getByTestId("legend-selection")).toHaveText("Selected: 0 – 20")
  await bins.nth(1).hover()
  await expect(page.getByTestId("legend-hover")).toHaveText("Hovered: 20 – 40")
  await page.mouse.move(0, 0)
  await expect(page.getByTestId("legend-hover")).toHaveText("Hovered: None")
})

test("number drafts and option dialogs work with native keyboard input after resize", async ({ page }) => {
  await page.getByRole("button", { name: /Amount: 2/ }).click()
  const amount = page.getByRole("spinbutton", { name: "Amount" })
  await amount.fill("")
  await amount.pressSequentially("-5")
  await expect(amount).toHaveValue("-5")
  await expect(page.getByRole("button", { name: /Amount: -5/ })).toBeVisible()
  await amount.fill("500")
  await amount.press("Enter")
  await expect(amount).toHaveValue("10")
  await amount.press("Escape")
  const trigger = page.getByRole("button", { name: /Region: West/ })
  await trigger.click()
  await expect(page.getByRole("option", { name: "West, 12 results" })).toBeVisible()
  await page.setViewportSize({ width: 400, height: 650 })
  const dialog = page.getByRole("dialog", { name: "Region" })
  await expect.poll(async () => {
    const box = await dialog.boundingBox()
    return Boolean(box && box.x >= 15 && box.x + box.width <= 385 && box.y >= 15 && box.y + box.height <= 635)
  }).toBe(true)
  await page.getByRole("searchbox", { name: "Search Region" }).fill("New")
  await page.keyboard.press("ArrowDown")
  await page.keyboard.press("Space")
  await expect(dialog).toBeHidden()
  await expect(page.getByRole("button", { name: /Region: New York/ })).toBeFocused()
})

test("point hover survives resize and details restore keyboard focus", async ({ page }) => {
  const errors: string[] = []
  page.on("pageerror", (error) => errors.push(error.message))
  const chart = page.getByTestId("point-chart")
  const canvas = chart.locator("canvas").first()
  const tooltip = chart.locator(".stream-frame-tooltip")
  for (const width of [500, 380]) {
    if (width === 380) await page.getByRole("button", { name: "Resize and shrink" }).click()
    await expect(canvas).toHaveCSS("width", `${width}px`)
    await canvas.hover({ position: { x: 40 + (width - 60) / 2, y: 140 } })
    await expect(tooltip).toHaveText("Point Alpha: 5, 5")
    const bounds = (await chart.boundingBox())!
    const tip = (await tooltip.boundingBox())!
    expect(tip.x).toBeGreaterThanOrEqual(bounds.x)
    expect(tip.x + tip.width).toBeLessThanOrEqual(bounds.x + bounds.width)
    expect(tip.y).toBeGreaterThanOrEqual(bounds.y)
    expect(tip.y + tip.height).toBeLessThanOrEqual(bounds.y + bounds.height)
    await page.mouse.move(0, 0)
    await expect(tooltip).toBeHidden()
  }
  await canvas.click({ position: { x: 200, y: 140 } })
  const details = page.getByRole("dialog", { name: "Point details" })
  await expect(details).toHaveText(/Selected point: Alpha/)
  await details.press("Escape")
  await expect(details).toBeHidden()
  const trigger = page.getByRole("button", { name: "Inspect by keyboard" })
  await trigger.focus()
  await page.keyboard.press("Enter")
  await expect(details).toBeFocused()
  await expect(details).toContainText("Keyboard Alpha")
  await page.keyboard.press("Escape")
  await expect(trigger).toBeFocused()
  expect(errors).toEqual([])
})

test("mobile controls announce dates, zoom substantially, and restore sheet focus", async ({ page }) => {
  await page.emulateMedia({ reducedMotion: "reduce" })
  await expect(page.getByRole("slider", { name: "Reporting date start" })).toHaveAttribute("aria-valuetext", "2026-01-01")
  const before = Number(await page.getByTestId("range-span").textContent())
  await page.getByRole("button", { name: "Zoom in" }).click()
  expect(Number(await page.getByTestId("range-span").textContent())).toBeLessThan(before * 0.95)
  const chip = page.getByRole("group", { name: "Chart views" }).getByRole("button", { name: "By region" })
  await chip.click()
  await expect(chip).toHaveAttribute("aria-pressed", "true")
  const toggle = page.getByRole("button", { name: /^(Show|Hide) details$/ })
  await toggle.click()
  await expect(page.getByRole("region", { name: "Mobile details" })).toBeFocused()
  const close = page.getByRole("button", { name: "Close", exact: true })
  for (const target of [chip, toggle, close]) {
    const box = (await target.boundingBox())!
    expect(box.width).toBeGreaterThanOrEqual(44)
    expect(box.height).toBeGreaterThanOrEqual(44)
  }
  await close.click()
  await expect(toggle).toBeFocused()
  await expect(toggle).toHaveAttribute("aria-expanded", "false")
})

test("open and empty editors, grouped legends, and mobile details have valid ARIA relationships", async ({ page }) => {
  await page.getByRole("button", { name: /Region: West/ }).click()
  const audit = () => new AxeBuilder({ page })
    .include("[aria-label='Legends']")
    .include("[aria-label='Sentence controls']")
    .include(".semiotic-mobile-chart-shell")
    .withRules(["aria-allowed-attr", "aria-prohibited-attr", "aria-required-children", "aria-required-parent", "aria-valid-attr-value", "button-name", "label"])
    .analyze()
  expect((await audit()).violations).toEqual([])
  await page.getByRole("searchbox", { name: "Search Region" }).fill("Not an option")
  await expect(page.getByText("No options found.")).toBeVisible()
  expect((await audit()).violations).toEqual([])
  await page.keyboard.press("Escape")
  await page.getByRole("button", { name: "Show details" }).click()
  expect((await audit()).violations).toEqual([])
})
